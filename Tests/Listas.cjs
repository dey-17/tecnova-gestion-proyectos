const assert = require('node:assert/strict');
const { filter, paginate, deadline } = require('../Tecnova.Proyectos.Web/Scripts/listas.js');
const rows = Array.from({length:26}, (_,i) => ({Id:i+1,Titulo:'Revisión '+i,Proyecto:'Portal',Asignado:'María',IdAsignado:2,IdEstado:10,IdPrioridad:1,FechaVencimiento:'2026-11-13'}));
assert.equal(paginate(rows,1,10).items.length,10);
assert.deepEqual(paginate(rows,3,10).items.map(x=>x.Id),[21,22,23,24,25,26]);
assert.equal(paginate(rows,99,10).page,3);
assert.equal(paginate([],3,10).from,0);
assert.equal(paginate(rows,-1,0).size,10);
assert.equal(filter(rows,{search:'revision',owner:'2',priority:'1',from:'2026-11-13',to:'2026-11-13'},'tareas').length,26);
assert.equal(filter(rows,{owner:'3'},'tareas').length,0);
assert.equal(filter(rows,{from:'2026-11-14'},'tareas').length,0);
assert.equal(deadline(rows[0],'2026-11-14').kind,'overdue');
assert.equal(deadline(rows[0],'2026-11-13').text,'Vence hoy');
assert.equal(deadline(rows[0],'2026-11-10').days,3);
assert.equal(deadline(rows[0],'2026-11-09'),null);
assert.equal(deadline({...rows[0],IdEstado:12},'2026-11-15'),null);
assert.equal(deadline({...rows[0],IdEstado:13},'2026-11-15'),null);
assert.equal(filter(rows,{due:'soon'},'tareas','2026-11-10').length,26);
assert.equal(filter(rows,{due:'soon'},'tareas','2026-11-14').length,0);
assert.equal(filter(rows,{due:'overdue'},'tareas','2026-11-14').length,26);
console.log('PASS: filtros combinados, límites de paginación y vencimientos UTC.');
